export function ParticipationIconBadge({
  name,
  variant = "teal",
  size = 32,
}: {
  name: Exclude<ParticipationIconName, "chevron-right" | "check" | "shield">;
  variant?: "teal" | "terracotta";
  size?: number;
}) {
  const gradientId = `badge-grad-${name}`;
  const colors =
    variant === "teal"
      ? { from: "#d4efef", to: "#b5dfe3", border: "#9dd0d5", text: "text-[#2a7a80]" }
      : { from: "#fde8e0", to: "#f5cfc0", border: "#e8b5a5", text: "text-terracotta" };

  return (
    <span
      className={["inline-flex items-center justify-center shrink-0 relative", colors.text].join(" ")}
      style={{ width: size, height: size }}
      aria-hidden
    >
      <svg
        viewBox="0 0 100 100"
        className="absolute inset-0 w-full h-full"
        aria-hidden
      >
        <defs>
          <radialGradient id={gradientId} cx="40%" cy="35%" r="60%">
            <stop offset="0%" stopColor={colors.from} />
            <stop offset="100%" stopColor={colors.to} />
          </radialGradient>
        </defs>
        <circle cx="50" cy="50" r="48" fill={`url(#${gradientId})`} stroke={colors.border} strokeWidth="1.5" />
      </svg>
      <ParticipationIcon name={name} size={Math.round(size * 0.65)} className="relative z-10" />
    </span>
  );
}