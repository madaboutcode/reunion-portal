#!/usr/bin/env node
/**
 * Downloads Google Fonts as self-hosted WOFF2 files.
 * Output: src/web/public/fonts/*.woff2 + src/web/src/fonts.generated.css
 * Run: node scripts/download-fonts.mjs
 */

import https from 'node:https';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const FONTS_DIR = path.join(ROOT, 'src/web/public/fonts');
const CSS_OUT = path.join(ROOT, 'src/web/src/fonts.generated.css');

const FONTS_URL =
  'https://fonts.googleapis.com/css2' +
  '?family=Caveat:wght@400;600;700' +
  '&family=DM+Sans:opsz,wght@9..40,400;9..40,500;9..40,600;9..40,700' +
  '&family=Playfair+Display:ital,wght@0,400;0,600;0,700;1,400' +
  '&family=Noto+Sans+Malayalam:wght@400;600;700' +
  '&display=swap';

// Chrome UA — required to receive WOFF2 responses from Google Fonts
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';

function get(url, headers = {}) {
  return new Promise((resolve, reject) => {
    https
      .get(url, { headers }, (res) => {
        if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
          resolve(get(res.headers.location, headers));
          return;
        }
        if (res.statusCode !== 200) {
          reject(new Error(`HTTP ${res.statusCode} for ${url}`));
          return;
        }
        const chunks = [];
        res.on('data', (c) => chunks.push(c));
        res.on('end', () => resolve(Buffer.concat(chunks)));
        res.on('error', reject);
      })
      .on('error', reject);
  });
}

function slugify(str) {
  return str.toLowerCase().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, '');
}

async function main() {
  fs.mkdirSync(FONTS_DIR, { recursive: true });

  console.log('Fetching font CSS from Google Fonts…');
  const css = (await get(FONTS_URL, { 'User-Agent': UA })).toString();

  // Each @font-face block is preceded by a /* subset */ comment
  const blockRe =
    /\/\*\s*([^*]+?)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g;

  const faces = [];
  let m;

  while ((m = blockRe.exec(css)) !== null) {
    const subset = m[1].trim();
    const body = m[2];

    const family = body.match(/font-family:\s*['"]?([^;'"]+)['"]?/)?.[1]?.trim();
    const style = body.match(/font-style:\s*([^;\s}]+)/)?.[1]?.trim() ?? 'normal';
    const weight = body.match(/font-weight:\s*([^;]+)/)?.[1]?.trim().replace(/\s+/g, '-');
    const display = body.match(/font-display:\s*([^;\s}]+)/)?.[1]?.trim() ?? 'swap';
    const srcUrl = body.match(/src:\s*url\(([^)]+)\)/)?.[1]?.trim();
    const unicodeRange = body.match(/unicode-range:\s*([^;]+)/)?.[1]?.trim();

    if (!family || !srcUrl) continue;

    const filename = `${slugify(family)}-${weight}-${style}-${slugify(subset)}.woff2`;
    faces.push({ family, style, weight, display, unicodeRange, srcUrl, filename });
  }

  if (faces.length === 0) {
    throw new Error('No @font-face blocks found — Google Fonts response may have changed.');
  }

  // Download font files
  for (const face of faces) {
    const dest = path.join(FONTS_DIR, face.filename);
    process.stdout.write(`  ↓ ${face.filename} … `);
    const buf = await get(face.srcUrl);
    fs.writeFileSync(dest, buf);
    console.log(`${buf.length} bytes`);
  }

  // Write generated CSS
  const lines = ['/* Generated by scripts/download-fonts.mjs — do not edit */\n'];
  for (const face of faces) {
    lines.push('@font-face {');
    lines.push(`  font-family: '${face.family}';`);
    lines.push(`  font-style: ${face.style};`);
    lines.push(`  font-weight: ${face.weight};`);
    lines.push(`  font-display: ${face.display};`);
    lines.push(`  src: url('/fonts/${face.filename}') format('woff2');`);
    if (face.unicodeRange) lines.push(`  unicode-range: ${face.unicodeRange};`);
    lines.push('}\n');
  }
  fs.writeFileSync(CSS_OUT, lines.join('\n'));

  console.log(`\n✓ ${faces.length} font faces written to src/web/public/fonts/`);
  console.log(`✓ CSS written to src/web/src/fonts.generated.css`);
}

main().catch((e) => {
  console.error('download-fonts failed:', e.message);
  process.exit(1);
});
